# Status-Override — sonst fehlen die bitv_steps-Einträge in BY_TEST_ID und
# get_test() liefert für alle bitv_-Tests None (siehe Fuß des Moduls).


def get_test(test_id: str) -> dict | None:
    return BY_TEST_ID.get(test_id)


def get_tests_for_suite(suite: str) -> list[dict]:
    """Gibt alle Registry-Einträge einer Suite zurück (bitv | wcag | all)."""
    if suite == "all":
        return list(REGISTRY)
    return [e for e in REGISTRY if e["suite"] == suite]


def get_syntax_tests(suite: str) -> list[dict]:
    return [e for e in get_tests_for_suite(suite) if e["type"] == "syntax"]


def get_resolution_tests(suite: str) -> list[dict]:
    return [e for e in get_tests_for_suite(suite) if e["type"] == "resolution"]


def get_manual_tests(suite: str) -> list[dict]:
    return [e for e in get_tests_for_suite(suite) if e["type"] == "manual"]


def get_stub_tests(suite: str) -> list[dict]:
    return [e for e in get_tests_for_suite(suite) if e["status"] == "stub"]


def get_implemented_tests(suite: str) -> list[dict]:
    return [e for e in get_tests_for_suite(suite) if e["status"] == "implemented"]


def get_implemented_test_ids(suite: str) -> list[str]:
    return [e["test_id"] for e in get_implemented_tests(suite)]


def get_stub_test_ids(suite: str) -> list[str]:
    return [e["test_id"] for e in get_stub_tests(suite)]


def validate_registry() -> list[str]:
    """Integritätsprüfung — wird von pytest genutzt. Gibt Warnungen zurück."""
    warnings: list[str] = []
    valid_levels = {"MUSS", "SOLLTE", "KANN"}
    valid_wcag_levels = {"", "A", "AA", "AAA"}
    valid_types = {"syntax", "resolution", "manual"}
    valid_statuses = {"implemented", "stub", "manual"}
    valid_suites = {"bitv", "wcag"}
    valid_categories = {"BITV", "WCAG", "EN 301 549"}
    for e in REGISTRY:
        if e["level"] not in valid_levels:
            warnings.append(f"{e['test_id']}: ungültiges level {e['level']!r}")
        if e["wcag_level"] not in valid_wcag_levels:
            warnings.append(f"{e['test_id']}: ungültiges wcag_level {e['wcag_level']!r}")
        if e["type"] not in valid_types:
            warnings.append(f"{e['test_id']}: ungültiger type {e['type']!r}")
        if e["status"] not in valid_statuses:
            warnings.append(f"{e['test_id']}: ungültiger status {e['status']!r}")
        if e["suite"] not in valid_suites:
            warnings.append(f"{e['test_id']}: ungültige suite {e['suite']!r}")
        if e["category"] not in valid_categories:
            warnings.append(f"{e['test_id']}: ungültige category {e['category']!r}")
        if e["type"] == "manual" and e["status"] != "manual":
            warnings.append(f"{e['test_id']}: type=manual erfordert status=manual")
        if e["status"] == "manual" and e["type"] != "manual":
            warnings.append(f"{e['test_id']}: status=manual erfordert type=manual")
        if e["status"] != "manual" and not e.get("check"):
            warnings.append(f"{e['test_id']}: status != manual ohne check-Funktion")
        if e["status"] == "manual" and e.get("check"):
            warnings.append(f"{e['test_id']}: status=manual mit check-Funktion")
    return warnings


