# ---------------------------------------------------------------------------
# EN 301 549 → Quell-Kriterien (BITV/WCAG)
# ---------------------------------------------------------------------------
# EN 301 549 übernimmt die Kriterien der WCAG 2.1 (Kapitel 9) und die der
# übrigen Kapitel aus der EN-/BITV-Nummerierung. Die Zuordnung läuft über die
# `id`: EN-Tests teilen sich die id mit ihrem Quell-Kriterium (BITV 6.1 ↔
# EN 6.1, EN 1.4.8 ↔ WCAG 1.4.8). Zusätzlich wird für EN-9.x-IDs das
# WCAG-Pendant ohne "9." und für WCAG-style IDs das BITV-9.x-Pendant ergänzt.
_EN_NON_WEB_CHAPTERS = {"5", "6", "7", "8", "9", "10", "11", "12", "13"}


def get_en_source_test_ids(test_id: str) -> list[str]:
    """Für einen EN-301-549-Test die zugrunde liegenden BITV-/WCAG-Test-IDs.

    Das EN-Kriterium wird separat ausgewiesen, bewertet wird aber über die
    Quell-Kriterien (das Ergebnis wird geerbt, siehe results.py).
    """
    entry = BY_TEST_ID.get(test_id)
    if entry is None or entry.get("category") != "EN 301 549":
        return []
    nid = entry.get("id") or ""
    first = nid.split(".", 1)[0] if nid else ""
    sources: list[str] = []

    def _add(cand_test_id: str) -> None:
        if cand_test_id not in sources:
            sources.append(cand_test_id)

    # 1) Gleiche id (deckt EN/BITV-Kapitel 5–13 und WCAG-style IDs ab)
    for cand in BY_ID.get(nid, []):
        if cand["category"] in ("BITV", "WCAG"):
            _add(cand["test_id"])
    # 2) EN-9.x-IDs → WCAG-Pendant ohne das "9."-Präfix (z. B. 9.1.3.2 → 1.3.2)
    if nid.startswith("9."):
        for cand in BY_ID.get(nid[2:], []):
            if cand["category"] == "WCAG":
                _add(cand["test_id"])
    # 3) WCAG-style IDs (z. B. 1.4.8) → BITV-Pendant mit "9."-Präfix (9.1.4.8)
    elif first not in _EN_NON_WEB_CHAPTERS:
        for cand in BY_ID.get("9." + nid, []):
            if cand["category"] == "BITV":
                _add(cand["test_id"])
    return sources
