def _build_index() -> tuple[dict, dict]:
    """Baut {test_id: entry} und {id: [entries]} auf und validiert Eindeutigkeit."""
    by_test_id: dict = {}
    by_id: dict[str, list] = {}
    seen_test_ids: set[str] = set()
    for entry in REGISTRY:
        test_id = entry["test_id"]
        if test_id in seen_test_ids:
            raise ValueError(f"Doppelte test_id im Registry: {test_id}")
        seen_test_ids.add(test_id)
        by_test_id[test_id] = entry
        by_id.setdefault(entry["id"], []).append(entry)
    return by_test_id, by_id


